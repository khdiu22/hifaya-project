# تسجيل دالة badge كفلتر مخصص في قوالب Django
@register.filter
def badge(value):
    # البحث عن اسم كلاس CSS المناسب للحالة المدخلة
    # إذا كانت الحالة غير موجودة في القاموس، استخدم badge-review
    return BADGES.get(value, "badge-review")
